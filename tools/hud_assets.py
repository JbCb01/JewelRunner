def outline(img):
    w, h = img.size
    out = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    src = img.load()
    dst = out.load()
    for y in range(h):
        for x in range(w):
            if src[x, y][3]:
                dst[x, y] = src[x, y]
                continue
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < w and 0 <= ny < h and src[nx, ny][3] and src[nx, ny][:3] != P['j']:
                        dst[x, y] = P['j'] + (255,)
    return out


def build_font(name, scale, space_w):
    cells = []
    for ch, rows in G.items():
        w = len(rows[0])
        g = Image.new('RGBA', (w * scale + 2, 9 * scale + 2), (0, 0, 0, 0))
        for r, row in enumerate(rows):
            for c, b in enumerate(row):
                if b == '#':
                    for sy in range(scale):
                        for sx in range(scale):
                            g.putpixel((1 + c * scale + sx, 1 + r * scale + sy), P['o'] + (255,))
        cells.append((ch, outline(g), w * scale))
    cols = 16
    cw = max(c[1].width for c in cells)
    chh = cells[0][1].height
    sheet = Image.new('RGBA', (cols * cw, ((len(cells) + cols - 1) // cols) * chh), (0, 0, 0, 0))
    lines = []
    for i, (ch, im, w) in enumerate(cells):
        x, y = (i % cols) * cw, (i // cols) * chh
        sheet.alpha_composite(im, (x, y))
        lines.append(f'char id={ord(ch)} x={x} y={y} width={im.width} height={im.height} xoffset=0 yoffset=0 xadvance={w + scale} page=0 chnl=15')
    lines.append(f'char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance={space_w} page=0 chnl=15')
    line_h = 9 * scale + 2
    base = 7 * scale + 1
    sheet.save(os.path.join(OUT, f'{name}.png'))
    fnt = [f'info face="{name}" size={line_h} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0 outline=0',
           f'common lineHeight={line_h} base={base} scaleW={sheet.width} scaleH={sheet.height} pages=1 packed=0',
           f'page id=0 file="{name}.png"', f'chars count={len(lines)}'] + lines + ['kernings count=0']
    open(os.path.join(OUT, f'{name}.fnt'), 'w', newline='\n').write('\n'.join(fnt) + '\n')
    return sheet


